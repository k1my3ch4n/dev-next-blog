export const getPosts = (tag = "", orderBy = "DESC"): PostData[] => {
  const filtered = tag
    ? BLOG_POSTS.filter((post) => post.tags.includes(tag))
    : [...BLOG_POSTS];
  return orderBy.toUpperCase() === "DESC" ? filtered.reverse() : filtered;
};

export const getPost = (postKey: string): PostData | null => {
  return BLOG_POSTS.find((post) => post.postKey === postKey) ?? null;
};

export const getAllTags = (): string[] => {
  const tags = new Set<string>();
  BLOG_POSTS.forEach((post) => post.tags.forEach((tag) => tags.add(tag)));
  return Array.from(tags).sort();
};

